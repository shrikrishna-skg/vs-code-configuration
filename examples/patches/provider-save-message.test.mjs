import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import {patch} from './provider-save-message.mjs';
const target=process.argv[2]??new URL('../stock/extension/dist/webview.js',import.meta.url);
const source=patch(fs.readFileSync(target,'utf8'));
const name=['JD','dR','TQ'].find(name=>source.includes(`function ${name}(e){let t=new Map,n=e.onMessage`));
assert.ok(name,'known provider helper');
const start=source.indexOf(`function ${name}(`),tail='return{clear:a,send:r,dispose:i}}',end=source.indexOf(tail,start)+tail.length;
const make=vm.runInNewContext(`(${source.slice(start,end)})`,{crypto:webcrypto});
const proxiedOutput=new Proxy(['text'],{}),model={input:['text'],output:proxiedOutput};
let receive, sent, error, connected=0, saving=true;
const bridge={onMessage(fn){receive=fn;return()=>{}},postMessage(message){sent=structuredClone(message)}};
const client=make(bridge);
const id=client.send({type:'saveCustomProvider',providerID:'sample',config:{models:{example:{modalities:model,variants:{high:new Proxy({reasoningEffort:'high'}, {})}}},env:new Proxy(['EXAMPLE_API_KEY'],{})},apiKey:'test-placeholder',apiKeyChanged:true},{onConnected(){connected++;saving=false},onError(e){error=e;saving=false}});
assert.ok(sent,'Provider request must reach the native bridge');
assert.equal(sent.config.models.example.modalities.output[0],'text');
assert.equal(sent.config.models.example.variants.high.reasoningEffort,'high');
assert.equal(sent.config.env[0],'EXAMPLE_API_KEY');
assert.equal(sent.apiKey,'test-placeholder');
assert.equal(sent.apiKeyChanged,true);
assert.equal(saving,true);
receive({type:'providerConnected',requestId:id});
assert.equal(saving,false);assert.equal(connected,1);assert.equal(error,undefined);
receive({type:'providerConnected',requestId:id});assert.equal(connected,1);
// A synchronous native-send failure must clear pending state and invoke the form error handler.
let callbackCount=0,failedId;
const broken=make({onMessage(fn){receive=fn;return()=>{}},postMessage(){throw new Error('test bridge failure')}});
failedId=broken.send({type:'saveCustomProvider',providerID:'sample'},{onError(e){callbackCount++;assert.equal(e.message,'Unable to send provider request. Please reopen settings and try again.')}});
assert.equal(callbackCount,1);
receive({type:'providerActionError',requestId:failedId});assert.equal(callbackCount,1);
const cyclic={};cyclic.self=cyclic;
broken.send({type:'saveCustomProvider',providerID:'sample',config:cyclic},{onError(){callbackCount++}});
assert.equal(callbackCount,2);
client.dispose();broken.dispose();
console.log('PASS: reactive provider data is cloneable, completion clears saving, synchronous failures clear pending callbacks.');
