import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { minimalConfig, agentName } from '../examples/cto/minimal/profile.mjs';
import { launchOptions } from './run-minimal-cto.mjs';
import { addMinimalTask } from './install-minimal-cto.mjs';
import { spawnSync } from 'node:child_process';

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'minimal-cto-test-'));
try {
  const ponytail = path.join(temp, 'AGENTS.md');
  fs.writeFileSync(ponytail, '# Canonical policy fixture');
  const live = { model: 'old/model', instructions: ['old-policy.md'], permission: { edit: 'ask', bash: { 'danger *': 'deny' } }, provider: { selected: { models: {} } }, agent: { old: { prompt: 'Old rules' } }, mcp: { desktop: { type: 'local', command: ['original'], enabled: true } } };
  const before = structuredClone(live);
  const options = { model: 'selected/model', variant: 'high', ponytail, directory: temp };
  const config = minimalConfig(live, options);
  assert.deepEqual(live, before, 'live configuration mutated');
  assert.deepEqual(config.provider, live.provider);
  assert.deepEqual(config.permission, live.permission);
  assert.deepEqual(config.instructions, [ponytail]);
  assert.deepEqual(Object.keys(config.agent), [agentName]);
  assert.equal(config.agent[agentName].permission.task, 'deny');
  assert.equal(config.agent[agentName].model, options.model);
  assert.equal(config.agent[agentName].variant, options.variant);
  assert.equal(config.mcp.desktop.enabled, false);
  assert.equal(config.subagent_depth, 0);
  assert.deepEqual(config.command, {});
  assert(!config.agent[agentName].prompt.includes('Old rules'));
  const { args } = launchOptions(live, options);
  assert(!args.includes('--auto'), 'interactive launch must preserve permission prompts');
  assert(args.includes('--interactive'));
  assert.equal(args[args.indexOf('--model') + 1], 'selected/model');
  assert.throws(() => minimalConfig(live, { ...options, model: '' }), /explicit/);
  assert.throws(() => minimalConfig(live, { ...options, ponytail: path.join(temp, 'absent') }), /ENOENT/);
  const originalTasks = { version: '2.0.0', tasks: [{ label: 'Keep', command: 'original' }], inputs: [{ id: 'keep', type: 'promptString' }] };
  const merged = addMinimalTask(originalTasks);
  assert.deepEqual(merged.tasks[0], originalTasks.tasks[0]);
  assert.deepEqual(merged.inputs[0], originalTasks.inputs[0]);
  assert.deepEqual(addMinimalTask(merged), merged, 'task installation must be idempotent');
  assert.equal(originalTasks.tasks.length, 1, 'task merge mutated user data');
  const taskFile = path.join(temp, 'tasks.json');
  fs.writeFileSync(taskFile, JSON.stringify(originalTasks));
  const install = args => spawnSync(process.execPath, [new URL('./install-minimal-cto.mjs', import.meta.url).pathname, ...args], { env: { ...process.env, MINIMAL_CTO_TASK_FILE: taskFile }, encoding: 'utf8' });
  assert.equal(install([]).status, 0);
  assert.deepEqual(JSON.parse(fs.readFileSync(taskFile)), originalTasks, 'dry-run wrote the user file');
  assert.equal(install(['--apply']).status, 0);
  assert.deepEqual(JSON.parse(fs.readFileSync(taskFile)), merged);
  assert.equal(fs.readdirSync(temp).filter(f => f.endsWith('.bak')).length, 1);
  assert.equal(install(['--apply']).status, 0);
  assert.equal(fs.readdirSync(temp).filter(f => f.endsWith('.bak')).length, 1, 'no-op install created another backup');
  console.log('PASS: isolated minimal instructions, canonical policy required, explicit model/effort, preserved permissions/providers, no automatic approval, delegation disabled, live config unmodified.');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
