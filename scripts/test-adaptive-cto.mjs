import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { addAdaptiveTasks } from './install-adaptive-cto.mjs';
import { spawnSync } from 'node:child_process';

const temp = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'adaptive-cto-test-')));
Object.assign(process.env, { CTO_STATE_DIR: path.join(temp, 'state'), CTO_AGENT_DIR: path.join(temp, 'agents'), CTO_CONFIG: path.join(temp, 'config.json'), CTO_PONYTAIL_FILE: path.join(temp, 'Ponytail.md'), CTO_KILO_BINARY: path.join(temp, 'fake-kilo') });
fs.mkdirSync(process.env.CTO_AGENT_DIR);
fs.writeFileSync(process.env.CTO_PONYTAIL_FILE, '# Canonical test policy');
fs.writeFileSync(process.env.CTO_CONFIG, '{}');
for (const name of ['deepseek-implementer', 'glm-investigator', 'luna-utility']) fs.writeFileSync(path.join(process.env.CTO_AGENT_DIR, name + '.md'), '---\nmodel: test/' + name + '\n---\n');
fs.writeFileSync(process.env.CTO_KILO_BINARY, `#!/usr/bin/env node
process.stdin.resume();process.stdin.on('end',()=>{console.log(JSON.stringify({type:'step_start'}));console.log(JSON.stringify({type:'text',part:{text:'Read-only CTO advice.'}}));console.log(JSON.stringify({type:'step_finish',part:{reason:'stop'}}));});`, { mode: 0o755 });
const m = await import('../examples/cto/manager.mjs');
const s = await import('../examples/cto/adaptive/session.mjs');
const p = await import('../examples/cto/adaptive/profile.mjs');
const repo = path.join(temp, 'repo'); fs.mkdirSync(repo);
m.git(repo, ['init']); m.git(repo, ['config', 'user.name', 'Test']); m.git(repo, ['config', 'user.email', 'test@localhost']);
fs.writeFileSync(path.join(repo, 'value.txt'), '1\n');
fs.writeFileSync(path.join(repo, 'removed.txt'), 'already removed by the user');
m.git(repo, ['add', '.']); m.git(repo, ['commit', '-m', 'initial']);
fs.unlinkSync(path.join(repo, 'removed.txt'));
fs.chmodSync(path.join(repo, 'value.txt'), 0o600);
const checks = [[process.execPath, '-e', 'if(!/^\\d+\\n$/.test(require("fs").readFileSync("value.txt","utf8"))) process.exit(1)']];
const input = { workspace: repo, role: 'implementer', title: 'Routine values', task: 'Update numeric value', acceptance: 'Only the numeric value changes', scopes: ['value.txt'], checks };
let job;
try {
  const existingTasks = { version: '2.0.0', tasks: [{ label: 'Keep this', command: 'original' }], inputs: [{ id: 'keep', type: 'promptString' }] };
  const taskConfig = addAdaptiveTasks(existingTasks, 'premium/cto');
  assert.deepEqual(addAdaptiveTasks(taskConfig, 'premium/cto'), taskConfig);
  assert.deepEqual(taskConfig.tasks[0], existingTasks.tasks[0]);
  assert.deepEqual(taskConfig.inputs[0], existingTasks.inputs[0]);
  assert.equal(existingTasks.tasks.length, 1);
  const fakeHome = path.join(temp, 'install');
  fs.mkdirSync(path.join(fakeHome, '.config/kilo'), { recursive: true });
  fs.writeFileSync(path.join(fakeHome, '.config/kilo/kilo.jsonc'), '{"model":"premium/cto"}');
  const install = args => spawnSync(process.execPath, [new URL('./install-adaptive-cto.mjs', import.meta.url).pathname, ...args], { env: { ...process.env, ADAPTIVE_CTO_HOME: fakeHome }, encoding: 'utf8' });
  const tasksFile = path.join(fakeHome, 'Library/Application Support/Code/User/tasks.json');
  assert.equal(install([]).status, 0); assert(!fs.existsSync(tasksFile));
  assert.equal(install(['--apply']).status, 0);
  assert.equal(JSON.parse(fs.readFileSync(tasksFile)).tasks.length, 3);
  assert(install(['--apply']).stdout.includes('"changed":false'));
  const live = { model: 'premium/cto', permission: { edit: { '*': 'allow', 'secret/**': 'deny' }, bash: { 'danger *': 'deny' } }, provider: { test: {} }, mcp: { unrelated: { enabled: true } } };
  const original = structuredClone(live);
  assert.equal(p.specialistModel('routine', process.env.CTO_AGENT_DIR), 'test/deepseek-implementer');
  assert.equal(p.specialistModel('utility', process.env.CTO_AGENT_DIR), 'test/luna-utility');
  const cto = p.adaptiveConfig(live, { mode: 'cto', model: live.model, ponytail: process.env.CTO_PONYTAIL_FILE });
  assert.equal(cto.mcp.cto.enabled, true); assert.equal(cto.mcp.unrelated.enabled, false);
  assert.equal(cto.agent[p.names.cto].permission['cto_*'], 'allow');
  assert.deepEqual(live, original);
  assert.deepEqual(m.workerConfig({ role: 'reviewer', writer: false, scopes: [], worktree: repo }, live).config.provider, live.provider, 'isolated worker lost custom provider routes');

  job = await s.createRoutine(input, 'test/deepseek');
  assert.equal(m.fingerprint(job.worktree, null), m.fingerprint(repo, null), 'snapshot changed a local deletion or non-executable file mode');
  fs.symlinkSync('missing-target', path.join(repo, 'dangling-link'));
  assert.notEqual(m.fingerprint(job.worktree, null), m.fingerprint(repo, null), 'broken symlink was ignored');
  fs.unlinkSync(path.join(repo, 'dangling-link'));
  const routine = p.adaptiveConfig(live, { mode: 'routine', model: 'test/deepseek', ponytail: process.env.CTO_PONYTAIL_FILE, sessionFile: '/private/session.json', contract: { ...job, intent: 'numeric values' } });
  const permissions = routine.agent[p.names.routine].permission;
  assert.equal(permissions.edit['*'], 'deny', 'global allow escaped scoped edit rules');
  assert.equal(permissions.edit['value.txt'], 'allow');
  assert.equal(permissions.edit['secret/**'], 'deny');
  assert.equal(permissions.bash, 'deny');
  assert.equal(routine.mcp.routine.enabled, true);
  assert.equal(routine.mcp.unrelated.enabled, false);
  assert.equal((await m.status()).activeWriters, 1);
  await assert.rejects(s.createRoutine(input, 'test/deepseek'), /occupied/);

  const write = value => fs.writeFileSync(path.join(job.worktree, 'value.txt'), value);
  write('42\n');
  assert.equal(fs.readFileSync(path.join(repo, 'value.txt'), 'utf8'), '1\n', 'unverified edit leaked');
  const first = await s.publish(job.id);
  assert(first.applied); assert.equal(first.revisions, 1);
  assert.equal(fs.readFileSync(path.join(repo, 'value.txt'), 'utf8'), '42\n');
  write('43\n'); assert.equal((await s.publish(job.id)).revisions, 2);
  assert.equal(fs.readFileSync(path.join(repo, 'value.txt'), 'utf8'), '43\n');
  assert.equal((await s.publish(job.id)).applied, false, 'unchanged publish created a revision');
  write('not a number\n');
  await assert.rejects(s.publish(job.id), /verification failed/);
  assert.equal(fs.readFileSync(path.join(repo, 'value.txt'), 'utf8'), '43\n');
  write('44\n'); fs.writeFileSync(path.join(job.worktree, 'outside.txt'), 'unexpected');
  await assert.rejects(s.publish(job.id), /scope/);
  assert(!fs.existsSync(path.join(repo, 'outside.txt')));
  fs.unlinkSync(path.join(job.worktree, 'outside.txt'));
  // A model cannot quietly modify the source through a competing editor.
  fs.writeFileSync(path.join(repo, 'value.txt'), '99\n');
  await assert.rejects(s.publish(job.id), /Destination changed/);
  assert.equal(fs.readFileSync(path.join(repo, 'value.txt'), 'utf8'), '99\n');
  fs.writeFileSync(path.join(repo, 'value.txt'), '43\n');
  fs.writeFileSync(path.join(repo, 'dependency.txt'), 'changed outside routine scope');
  await assert.rejects(s.publish(job.id), /Other project files changed/);
  assert.equal(fs.readFileSync(path.join(repo, 'value.txt'), 'utf8'), '43\n');
  fs.unlinkSync(path.join(repo, 'dependency.txt'));
  const advice = await s.consult(job.id, 'Review this numeric-only scope.', 'premium/cto', 'high', live);
  assert.equal(advice.model, 'premium/cto'); assert(advice.adviceOnly);
  assert.equal((await m.status()).activeWriters, 1);
  assert.equal((await m.status()).activeWorkers, 1, 'consultation leaked a capacity slot');
  await s.release(job.id); assert.equal((await m.status()).activeWorkers, 0);
  console.log('PASS: model routing, scoped permissions, shared ownership/capacity, repeated verified publication, failed-check and out-of-scope quarantine, source conflict protection, premium read-only consultation and lease release.');
} finally {
  if (job) await s.release(job.id);
  fs.rmSync(temp, { recursive: true, force: true });
}
